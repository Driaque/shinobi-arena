"""Normalize generated 4x4 RGBA sheets, retaining alpha and a common foot pivot.

Usage: python3 scripts/normalize-fighter-art.py /path/to/input-manifest.json
Manifest maps original character IDs to their generated source PNG paths.
Pillow is needed only to reproduce assets; CI consumes the committed WebPs/data.
"""
from pathlib import Path
import json
import sys
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'apps/web/assets/originals'
DEST.mkdir(parents=True, exist_ok=True)


def seam(alpha, expected, axis):
    """Prefer transparent gutters close to the nominal grid, avoiding cut feet."""
    w, h = alpha.size
    size = w if axis == 0 else h
    radius = int(size / 32)
    scores = []
    for value in range(max(1, expected-radius), min(size-1, expected+radius)):
        strip = alpha.crop((value, 0, value+1, h) if axis == 0 else (0, value, w, value+1))
        count = sum(1 for p in strip.tobytes() if p > 16)
        scores.append((count + abs(value-expected)*.25, value))
    return min(scores)[1]


def normalize(path):
    source = Image.open(path).convert('RGBA')
    alpha = source.getchannel('A')
    if alpha.getextrema()[0] == 255:
        raise ValueError(f'{path}: expected transparent alpha')
    ys = [0] + [seam(alpha, round(source.height*i/4), 1) for i in range(1, 4)] + [source.height]
    crops = []
    for row in range(4):
        band = source.crop((0, ys[row], source.width, ys[row+1]))
        ba = band.getchannel('A')
        xs = [0] + [seam(ba, round(source.width*i/4), 0) for i in range(1, 4)] + [source.width]
        for col in range(4):
            cell = band.crop((xs[col], 0, xs[col+1], band.height))
            mask = cell.getchannel('A').point(lambda p: 255 if p > 24 else 0)
            box = mask.getbbox()
            if not box:
                raise ValueError(f'{path}: empty cell {row*4+col}')
            cell = cell.crop(box)
            # Average the bottom contact band, rather than the whole silhouette:
            # an outstretched hand/flowing cape must not shift the body root.
            foot = cell.getchannel('A').crop((0, max(0, cell.height-12), cell.width, cell.height))
            weights = [sum(foot.getpixel((x,y)) for y in range(foot.height)) for x in range(foot.width)]
            pivot = sum(x*v for x, v in enumerate(weights))/max(1, sum(weights))
            crops.append((cell, pivot))
    standing = crops[0][0].height
    scale = min(300/standing, 320/max(c.height for c, _ in crops),
                180/max(p for _, p in crops), 180/max(c.width-p for c, p in crops))
    sheet = Image.new('RGBA', (1536, 1536))
    for i, (cell, pivot) in enumerate(crops):
        w, h = round(cell.width*scale), round(cell.height*scale)
        scaled = cell.resize((w, h), Image.Resampling.LANCZOS)
        x = (i%4)*384 + 192-round(pivot*scale)
        y = (i//4)*384 + 340-h
        sheet.alpha_composite(scaled, (x, y))
    return sheet, {'standingHeight': round(standing*scale), 'poses': 16}


manifest = json.loads(Path(sys.argv[1]).read_text())
data = {}
for identity, path in manifest.items():
    if identity not in {'silent','winta','dora','aren','eira','kael','nyra','rook','veyra','oryn'}:
        raise ValueError(f'Unknown original fighter: {identity}')
    sheet, data[identity] = normalize(path)
    sheet.save(DEST / f'{identity}.webp', 'WEBP', quality=90, method=6)
    print(identity, data[identity])
data_path = ROOT / 'packages/presentation/fighter-atlas-data.js'
data_path.write_text('// Generated by scripts/normalize-fighter-art.py.\nexport const FIGHTER_ATLAS_DATA = ' + json.dumps(data, indent=2) + ';\n')
