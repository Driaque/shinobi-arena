"""Pack transparent approved run exports without per-frame stretching.
Usage: python scripts/normalize-running-art.py /path/to/export-manifest.json
Manifest maps character id to transparent source path; Silent maps to [empty,equipped].
Background extraction is performed by imagegen, never by this packing script.
"""
import json,re,sys
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
roots={'winta':285,'dora':280,'aren':281,'eira':285,'kael':277,'nyra':279,'rook':277,'veyra':283,'oryn':278}
source=json.loads(Path(sys.argv[1]).read_text())
old=json.loads((ROOT/'packages/presentation/fighter-atlas-data.js').read_text().split(' = ',1)[1].rstrip(';\n'))
metadata=ROOT/'packages/presentation/running-atlas-data.js'
data=json.loads(metadata.read_text().split(' = ',1)[1].rstrip(';\n')) if metadata.exists() else {}
out=ROOT/'apps/web/assets/originals/runs';out.mkdir(parents=True,exist_ok=True)
for id,paths in source.items():
    paths=paths if isinstance(paths,list) else [paths]
    atlas=Image.new('RGBA',(1536,1536))
    for group,path in enumerate(paths):
        im=Image.open(path).convert('RGBA')
        assert im.getchannel('A').getextrema()==(0,255),f'{id}: transparency missing'
        rows=2 if id=='silent' else 4
        assert im.size==((1774,887) if id=='silent' else (1254,1254)),(id,im.size)
        for i in range(rows*4):
            col,row=i%4,i//4
            x,y=round(col*im.width/4),round(row*im.height/rows)
            right=round((col+1)*im.width/4)
            if id=='silent' and group==1 and col<3:right=min(x+490,im.width)
            left_trim=50 if id=='silent' and group==1 and col>0 else 0
            crop=im.crop((x+left_trim,y,right,round((row+1)*im.height/rows)))
            scale=.7 if id=='silent' else 1
            crop=crop.resize((round(crop.width*scale),round(crop.height*scale)),Image.Resampling.LANCZOS)
            rx,ry=(285,408) if id=='silent' else (210,roots[id])
            rx-=left_trim
            dest=i+group*8
            cell=Image.new('RGBA',(384,384));cell.alpha_composite(crop,(round(192-rx*scale),round(340-ry*scale)))
            # Reject atlas bleed; preserve a transparent gutter around each cell.
            assert not any(cell.getchannel('A').point(lambda a:255 if a>32 else 0).crop(box).getbbox() for box in [(0,0,384,2),(0,382,384,384),(0,0,2,384),(382,0,384,384)]),(id,i,'edge')
            atlas.alpha_composite(cell,((dest%4)*384,(dest//4)*384))
    oldim=Image.open(ROOT/f'apps/web/assets/originals/{id}.webp')
    oldbox=oldim.crop((768,0,1152,384)).getchannel('A').point(lambda a:255 if a>32 else 0).getbbox()
    newbox=atlas.crop((0,0,384,384)).getchannel('A').point(lambda a:255 if a>32 else 0).getbbox()
    height=round((newbox[3]-newbox[1])*old[id]['standingHeight']/(oldbox[3]-oldbox[1]))
    data[id]={'standingHeight':height,'poses':16}
    atlas.save(out/f'{id}.webp',format='WEBP',quality=92,method=4)
    print(id,height,(out/f'{id}.webp').stat().st_size)
(ROOT/'packages/presentation/running-atlas-data.js').write_text('// Generated by scripts/normalize-running-art.py.\nexport const RUNNING_ATLAS_DATA = '+json.dumps(data,indent=2)+';\n')
